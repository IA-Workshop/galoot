#!/usr/bin/env -S python3 -I
"""Writes units.toml and units-gcc.toml, the units of plan 0032's cost
campaign, from the list below and test/support/rational.hpp.

Run from this directory. The compile commands of text units carry no -I for
test/, so a unit over the test rational holds that header's text in place of
its include; the header is the same at both revisions measured.
"""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
RATIONAL = (HERE / "../../../../../test/support/rational.hpp").read_text()

SOURCES = [
    ("core/mv", "test/core/mv_test.cpp"),
    ("core/linear", "test/core/linear_test.cpp"),
    ("core/product", "test/core/product_test.cpp"),
    ("core/unary", "test/core/unary_test.cpp"),
    ("core/transform", "test/core/transform_test.cpp"),
    ("core/basis_change", "test/core/basis_change_test.cpp"),
    ("presets/rga3/objects", "test/presets/rga3/objects_test.cpp"),
    ("presets/rga3/motions", "test/presets/rga3/motions_test.cpp"),
]

# Each body is an out-of-line function, so that its kernel is compiled for
# run time. run_product is reached by apply onto the full layout, one term,
# so that its result has every place of full<n>.
BODIES = {
    "map": ("run_map", "Full convert(const Scalar& s) { return Full{s}; }"),
    "sum": ("run_sum",
            "Full add(const Full& a, const Full& b) { return a + b; }"),
    "apply": ("run_product",
              "Full onto(const Scalar& a, const Scalar& b) { return "
              "galoot::core::detail::apply<galoot::core::detail::"
              "BinaryOperation::geometric_product, galoot::core::full<N>>"
              "(a, b); }"),
    "product": ("run_product",
                "auto multiply(const Scalar& s, const Full& f) { return "
                "galoot::core::geometric_product(s, f); }"),
}
SCALARS = {"double": "double", "rational": "test_support::rational"}


def text(n, body, scalar):
    lines = ["#include <galoot/core.hpp>"]
    if scalar == "rational":
        lines.append(RATIONAL)
    lines += [
        "struct rn { static constexpr auto value = "
        f"galoot::core::R<{n}, 0, 0>(); }};",
        "inline constexpr galoot::core::blade_set<1> scalar_layout{"
        "std::array<galoot::core::oriented_blade, 1>{{{.mask = 0, "
        ".sign = 1}}}};",
        f"using Full = galoot::core::mv<rn, galoot::core::full<{n}>, "
        f"{SCALARS[scalar]}>;",
        f"using Scalar = galoot::core::mv<rn, scalar_layout, "
        f"{SCALARS[scalar]}>;",
        BODIES[body][1].replace("full<N>", f"full<{n}>"),
    ]
    return "\n".join(lines) + "\n"


def unit(name, comment, source_or_text):
    key, value = source_or_text
    value = json.dumps(value)
    return (f"\n{comment}[[unit]]\nname = \"{name}\"\n{key} = {value}\n"
            "trees = [\"before\", \"after\"]\nkind = \"debug\"\n")


def spec(head, compilers, cases):
    out = [head, f"compilers = {json.dumps(compilers)}\n",
           "flags_from = \"core.metric_type_width\"\n"]
    for name, comment, what in cases:
        out.append(unit(name, comment, what))
    return "".join(out)


HEAD = """# Generated by make_units.py. The units of plan 0032 criterion 6, for
# tools/compiles cost on the debug trees, before (6b8e2b6: the old kernels
# with the canaries) and after (the tip), so that each difference is the
# change of the kernels alone.
"""
both = [(name, "", ("source", src)) for name, src in SOURCES]
for body in ("map", "sum", "apply"):
    for scalar in SCALARS:
        both.append((f"places256/{body}_{scalar}",
                     f"# {BODIES[body][0]} at 256 places, full<8> of R(8,0,0), "
                     f"over {scalar}.\n", ("text", text(8, body, scalar))))
gcc = []
for body in ("map", "sum", "apply"):
    for scalar in SCALARS:
        gcc.append((f"places1024/{body}_{scalar}",
                    f"# {BODIES[body][0]} at 1,024 places, full<10> of "
                    f"R(10,0,0), over {scalar}.\n",
                    ("text", text(10, body, scalar))))
for scalar in SCALARS:
    gcc.append((f"terms512/product_{scalar}",
                "# run_product at 512 places with 512 terms, the scalar times "
                f"full<9> of R(9,0,0), over {scalar}.\n",
                ("text", text(9, "product", scalar))))

(HERE / "units.toml").write_text(spec(
    HEAD + "# The sources that instantiate the kernels, and text units at 256\n"
    "# places, the largest full layout Clang 23 builds an mv on at its\n"
    "# default limits.\n", ["gcc", "clang"], both))
(HERE / "units-gcc.toml").write_text(spec(
    HEAD + "# GCC only: text units at 1,024 places (full<10>), which Clang 23\n"
    "# does not build at its default limits, and a product of 512 terms\n"
    "# (scalar times full<10> fails on GCC 16 inside the plan's result\n"
    "# collection, outside the kernels).\n", ["gcc"], gcc))
