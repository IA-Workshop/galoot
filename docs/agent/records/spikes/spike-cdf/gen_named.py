"""Spike F: write a translation unit that reads named components.

The unit includes fixture.hpp and defines REPS functions. Each reads all 18
(type, name) pairs of the rga3 Point, Line, and Motor once, so the unit holds
18 distinct accesses and 18 * REPS uses. Three spellings:

  string     get<"e41">(l)         fixed-string class-type template argument
  index      get_at<0>(l)          integer template argument (baseline)
  subscript  l["e41"]              consteval-constructed parameter

Each function's accesses are summed into a volatile so nothing is folded at
-O0 or -O2. Variant `missing` replaces the last access of the first function
with a name not in the set, for the diagnostic.

Usage: python3 -I gen_named.py FORM REPS [missing] > named_tu.cpp
"""

import sys

TYPES = {
    "p": ("Point", ["e1", "e2", "e3", "e4"]),
    "l": ("Line", ["e41", "e42", "e43", "e23", "e31", "e12"]),
    "q": ("Motor", ["1", "e41", "e42", "e43", "e23", "e31", "e12", "e1234"]),
}


def access(form, var, i, name):
    if form == "string":
        return f'get<"{name}">({var})'
    if form == "index":
        return f"get_at<{i}>({var})"
    if form == "subscript":
        return f'{var}["{name}"]'
    raise SystemExit(f"unknown form {form}")


def main():
    form, reps = sys.argv[1], int(sys.argv[2])
    missing = len(sys.argv) > 3 and sys.argv[3] == "missing"
    out = ["// Generated by gen_named.py " + " ".join(sys.argv[1:]) + "; "
           "do not edit.",
           '#include "fixture.hpp"', "", "#include <cstddef>", "",
           "using namespace cdf;", "using namespace cdf::rga3_types;", "",
           "template <std::size_t I, class Alg, blade_set B, class T>",
           "constexpr const T& get_at(const mv<Alg, B, T>& x) {",
           "  return x.c[I];", "}", "", "volatile double sink = 0;", ""]
    for r in range(reps):
        out.append(f"void use{r}(const Point& p, const Line& l, "
                   "const Motor& q) {")
        terms = []
        for var, (_, names) in TYPES.items():
            for i, name in enumerate(names):
                terms.append(access(form, var, i, name))
        if missing and r == 0:
            terms[-1] = access(form, "l", 6, "e1")
        out.append("  sink = " + terms[0] + ";")
        for t in terms[1:]:
            out.append(f"  sink = sink + {t};")
        out.append("}")
    out += ["", "int main() {", "  [[maybe_unused]] const Point p{};",
            "  [[maybe_unused]] const Line l{};",
            "  [[maybe_unused]] const Motor q{};"]
    out += [f"  use{r}(p, l, q);" for r in range(reps)]
    out += ["  return 0;", "}", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
