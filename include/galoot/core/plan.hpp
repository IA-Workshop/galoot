#ifndef GALOOT_CORE_PLAN_HPP
#define GALOOT_CORE_PLAN_HPP

// The plan of a geometric product: for a multivector stored on one blade set
// times a multivector stored on another, every term e_A e_B of every pair of
// their blades, as exact data. A product of two such multivectors is then the
// sum, over the terms of the plan, of the coefficient of the term times the
// first input's coefficient at position a times the second's at position b,
// on the blade of the term.
//
// A blade set lists oriented blades, sign times the canonical blade of a
// mask, and a coefficient stored on one multiplies that signed blade. So the
// term of the blades s_a e_A and s_b e_B on e_C is s_a s_b c, for the
// coefficient c of e_C in e_A e_B, and the plan holds that product: the
// signs of the inputs are folded into the coefficients when the plan is
// generated. The output blade of every term is a canonical mask with sign
// +1.
//
// The plan is generated by one constexpr function, so the same code serves a
// constant evaluation and a run-time call. A program reads a plan through
// gp_plan, a variable template, so each translation unit evaluates a plan
// once for each algebra and pair of sets that it uses.

#include <array>
#include <cstddef>
#include <span>

#include <galoot/core/bits.hpp>
#include <galoot/core/blade_product.hpp>
#include <galoot/core/blade_set.hpp>
#include <galoot/core/metric.hpp>

namespace galoot::core::detail {

/// One term of a product plan: the blade at position `a` of the first set
/// times the blade at position `b` of the second contributes coefficient
/// times the canonical blade of the mask `out`.
///
/// Guarantees: an aggregate, trivially copyable; two terms are equal when
/// every member is.
struct plan_term {
  /// The position of the first factor's blade in the first set.
  std::size_t a;
  /// The position of the second factor's blade in the second set.
  std::size_t b;
  /// The generators of the output blade, with sign +1: bit i - 1 stands for
  /// e_i.
  mask_t out;
  /// The exact coefficient, with the signs of both input blades folded in.
  coefficient_type coefficient;

  /// Equal when every member is equal.
  [[nodiscard]] constexpr bool operator==(const plan_term&) const = default;
};

/// A term list capacity that suffices for every product of a blade of `as`
/// with a blade of `bs`: the largest product_capacity over the pairs, and at
/// least 1, so that it is a valid capacity when a set is empty.
///
/// Requires: nothing.
/// Guarantees: generate_gp<plan_capacity(as, bs)> never outgrows its term
/// lists, because product_capacity of a pair suffices for every list formed
/// while generating that pair's product.
[[nodiscard]] constexpr std::size_t
plan_capacity(std::span<const oriented_blade> as,
              std::span<const oriented_blade> bs) noexcept {
  std::size_t capacity = 1;
  for (const oriented_blade& x : as) {
    for (const oriented_blade& y : bs) {
      const std::size_t pair = product_capacity(x.mask, y.mask);
      // NOLINTNEXTLINE(readability-use-std-min-max): avoids <algorithm> here.
      if (pair > capacity) {
        capacity = pair;
      }
    }
  }
  return capacity;
}

/// Generates the plan of the geometric product of the blades of `as` with the
/// blades of `bs` in the metric `g`: for each position a of `as`, then each
/// position b of `bs`, the terms of e_A e_B in canonical order of their
/// blades, each with the coefficient s_a s_b c for the signs s_a and s_b of
/// the two blades. Writes the first out.size() terms to `out` and returns the
/// number of all terms, so a call with an empty `out` only counts them, and a
/// second call with `out` of that size writes them all.
///
/// Requires: every sign of `as` and `bs` is +1 or -1, which is not checked
/// here; every mask names only e_1 to e_N, and Capacity suffices for every
/// pair, as plan_capacity(as, bs) does, each checked by GALOOT_ASSERT in
/// blade_product. Every coefficient fits coefficient_type, checked by
/// GALOOT_ASSERT.
/// Guarantees: no term has a zero coefficient, and within one pair no blade
/// appears twice. A mask listed twice in a set is not rejected; each place
/// that lists it gets its own terms. Places of `out` past the number of terms
/// are not written.
template <std::size_t Capacity, std::size_t N>
constexpr std::size_t generate_gp(const metric<N>& g,
                                  std::span<const oriented_blade> as,
                                  std::span<const oriented_blade> bs,
                                  std::span<plan_term> out) noexcept {
  std::size_t count = 0;
  for (std::size_t a = 0; a < as.size(); ++a) {
    for (std::size_t b = 0; b < bs.size(); ++b) {
      const term_list<Capacity> product =
          blade_product<Capacity>(g, as[a].mask, bs[b].mask);
      // A sign of +1 or -1 times a coefficient within -max to max cannot
      // overflow, so the product needs no guard.
      const coefficient_type sign =
          static_cast<coefficient_type>(as[a].sign) * bs[b].sign;
      for (std::size_t k = 0; k < product.size(); ++k) {
        if (count < out.size()) {
          out[count] = {
              .a = a,
              .b = b,
              .out = product.terms[k].blade,
              .coefficient = sign * product.terms[k].coefficient,
          };
        }
        ++count;
      }
    }
  }
  return count;
}

// Whether every blade of `set` names only e_1 to e_n.
template <std::size_t K>
[[nodiscard]] constexpr bool all_in_algebra(const blade_set<K>& set,
                                            std::size_t n) noexcept {
  // NOLINTNEXTLINE(readability-use-anyofallof): avoids <algorithm> here.
  for (const oriented_blade& blade : set.blades) {
    if (!in_algebra(blade.mask, n)) {
      return false;
    }
  }
  return true;
}

// What is wrong with a generated plan, if anything. None of these can hold for
// a plan that generate_gp wrote; they are checked once per plan, because each
// check is one pass over the terms.
struct plan_defects {
  bool zero_coefficient;
  bool beyond_first;
  bool beyond_second;
  bool beyond_n;
  bool out_of_order;
};

// The defects of `plan` for sets of `first` and `second` blades in an algebra
// of n generators. The terms must come in order of a, then b, and within one
// pair in strictly increasing canonical order of their blades, so a blade
// listed twice for one pair is out of order too.
[[nodiscard]] constexpr plan_defects defects_of(std::span<const plan_term> plan,
                                                std::size_t first,
                                                std::size_t second,
                                                std::size_t n) noexcept {
  plan_defects found{};
  for (std::size_t k = 0; k < plan.size(); ++k) {
    const plan_term& t = plan[k];
    found.zero_coefficient = found.zero_coefficient || t.coefficient == 0;
    found.beyond_first = found.beyond_first || t.a >= first;
    found.beyond_second = found.beyond_second || t.b >= second;
    found.beyond_n = found.beyond_n || !in_algebra(t.out, n);
    if (k > 0) {
      const plan_term& before = plan[k - 1];
      const bool in_order = before.a < t.a ||
                            (before.a == t.a && before.b < t.b) ||
                            (before.a == t.a && before.b == t.b &&
                             canonical_less(before.out, t.out));
      found.out_of_order = found.out_of_order || !in_order;
    }
  }
  return found;
}

template <std::size_t Count, std::size_t Capacity, std::size_t N>
[[nodiscard]] constexpr std::array<plan_term, Count>
filled_gp(const metric<N>& g, std::span<const oriented_blade> as,
          std::span<const oriented_blade> bs) noexcept {
  std::array<plan_term, Count> plan{};
  generate_gp<Capacity>(g, as, bs, plan);
  return plan;
}

// Checks both sets once, before anything is generated, so that a misuse gives
// its own message and no other. Then counts the terms, fills an array of that
// size, and checks what is cheap to check of the result.
//
// Every local is static constexpr: its initializer is evaluated once, when
// the function is instantiated. Clang evaluates the initializer of a plain
// constexpr local again each time the call is evaluated, so the plan would be
// generated twice, once for the static_asserts and once for the call.
template <metric_like Alg, blade_set A, blade_set B>
consteval auto make_gp_plan() {
  static constexpr std::size_t n = Alg::value.generator_count;
  static constexpr bool in_range = all_in_algebra(A, n) && all_in_algebra(B, n);
  static constexpr bool valid_signs = signs_valid<A> && signs_valid<B>;
  static_assert(in_range, "gp plan: a blade set names a generator beyond e_n");
  static_assert(valid_signs,
                "gp plan: a blade set holds a sign other than +1 or -1");

  if constexpr (in_range && valid_signs) {
    static constexpr std::size_t capacity = plan_capacity(A.blades, B.blades);
    static constexpr std::size_t count =
        generate_gp<capacity>(Alg::value, A.blades, B.blades, {});
    static constexpr auto plan =
        filled_gp<count, capacity>(Alg::value, A.blades, B.blades);

    static constexpr plan_defects defects =
        defects_of(plan, A.size(), B.size(), n);
    static_assert(!defects.zero_coefficient,
                  "gp plan: a generated term has a zero coefficient");
    static_assert(!defects.beyond_first,
                  "gp plan: a generated term points past the first set");
    static_assert(!defects.beyond_second,
                  "gp plan: a generated term points past the second set");
    static_assert(!defects.beyond_n,
                  "gp plan: a generated term has a generator beyond e_n");
    static_assert(!defects.out_of_order,
                  "gp plan: generated terms are out of order or repeated");
    return plan;
  } else {
    return std::array<plan_term, 0>{};
  }
}

/// The plan of the geometric product of a multivector on the blade set A
/// with one on the blade set B, in the algebra of the tag Alg: a std::array
/// of plan_term, in order of a, then b, then canonical order of out, as
/// generate_gp writes it.
///
/// Requires: Alg is metric_like. Every blade of A and B names only e_1 to
/// e_n and has sign +1 or -1, each checked at compile time with a message
/// that names it. Every coefficient fits coefficient_type, checked as the
/// plan is generated. A mask listed twice in one set is not checked; each
/// place that lists it gets its own terms. The plan is a constant
/// evaluation, so the compiler's limits on constant evaluation bound the
/// size of the sets in practice. Measured at the default limits, alike at
/// -O0 and -O2 and with or without _GLIBCXX_ASSERTIONS: every blade times
/// every blade, full<n> with full<n>, builds for n up to 5 on Clang 23 and
/// up to 7 on GCC 16 in R(n,0,0), R(n-1,0,1), and conformal(n-2), and for n
/// up to 4 and 5 in a form with every entry nonzero, whose products have
/// more terms. Sets of a few blades cost what they use: four blades times
/// three at n = 16 build on both.
/// Guarantees: evaluated once in each translation unit for each Alg, A, and
/// B that it uses. No term has a zero coefficient, a refers to a position of
/// A and b to one of B, and out names only e_1 to e_n; each is checked when
/// the plan is generated.
template <metric_like Alg, blade_set A, blade_set B>
inline constexpr auto gp_plan = make_gp_plan<Alg, A, B>();

} // namespace galoot::core::detail

#endif // GALOOT_CORE_PLAN_HPP
