/// The products a plan can be generated for.
///
/// Guarantees: a structural type, so an operation can be a template
/// argument.
enum class BinaryOperation : std::uint8_t {
  /// The geometric product e_A e_B, from the metric.
  gp,
  /// The exterior product e_A ∧ e_B, which does not depend on the metric.
  wedge,
};

/// One term of a product plan: the blade at position `a` of the first set
/// times the blade at position `b` of the second contributes coefficient
/// times the canonical blade of the mask `out`.
///
/// Guarantees: an aggregate, trivially copyable; two terms are equal when
/// every member is.
struct plan_term {
  /// The position of the first factor's blade in the first set.
  std::size_t a;
  /// The position of the second factor's blade in the second set.
  std::size_t b;
  /// The generators of the output blade, with sign +1: bit i - 1 stands for
  /// e_i.
  mask_t out;
  /// The exact coefficient, with the signs of both input blades folded in.
  coefficient_type coefficient;

  /// Equal when every member is equal.
  [[nodiscard]] constexpr bool operator==(const plan_term&) const = default;
};

/// The largest number of terms that `op` gives one pair of blades, of the
/// masks `a` and `b`, in any metric: product_capacity(a, b) for the
/// geometric product, and 1 for the wedge.
///
/// Requires: nothing.
/// Guarantees: a term list of this capacity never overflows while the pair's
/// terms are generated.
[[nodiscard]] constexpr std::size_t pair_capacity(BinaryOperation op, mask_t a,
                                                  mask_t b) noexcept {
  return op == BinaryOperation::gp ? product_capacity(a, b) : 1;
}

/// A term list capacity that suffices for every pair of a blade of `as` with
/// a blade of `bs` under `op`: the largest pair_capacity over the pairs, and
/// at least 1, so that it is a valid capacity when a set is empty.
///
/// Requires: nothing.
/// Guarantees: generate_plan<op, plan_capacity(op, as, bs)> never outgrows
/// its term lists.
[[nodiscard]] constexpr std::size_t
plan_capacity(BinaryOperation op, std::span<const oriented_blade> as,
              std::span<const oriented_blade> bs) noexcept {
  std::size_t capacity = 1;
  for (const oriented_blade& x : as) {
    for (const oriented_blade& y : bs) {
      const std::size_t pair = pair_capacity(op, x.mask, y.mask);
      // NOLINTNEXTLINE(readability-use-std-min-max): avoids <algorithm> here.
      if (pair > capacity) {
        capacity = pair;
      }
    }
  }
  return capacity;
}

/// The terms that `Op` gives the blades of the masks `a` and `b` in the
/// metric `g`, in canonical order of their blades: blade_product for the
/// geometric product; for the wedge, nothing when the blades share a
/// generator, and otherwise reorder_sign(a, b) on the blade of a | b.
///
/// Requires: `a` and `b` name only e_1 to e_N, checked by GALOOT_ASSERT, and
/// Capacity >= pair_capacity(Op, a, b); for the geometric product, what
/// blade_product requires.
/// Guarantees: the result is exact, with no zero coefficient. The wedge reads
/// nothing of `g`.
template <BinaryOperation Op, std::size_t Capacity, std::size_t N>
[[nodiscard]] constexpr term_list<Capacity>
pair_terms(const metric<N>& g, mask_t a, mask_t b) noexcept {
  if constexpr (Op == BinaryOperation::gp) {
    return blade_product<Capacity>(g, a, b);
  } else {
    GALOOT_ASSERT(in_algebra(a | b, N), "blade has a generator beyond e_n");
    term_list<Capacity> out{};
    if ((a & b) == 0) {
      out.add(a | b, reorder_sign(a, b));
    }
    return out;
  }
}

/// Generates the plan of `Op` over the blades of `as` and `bs` in the metric
/// `g`: for each position a of `as`, then each position b of `bs`, the terms
/// of the pair in canonical order of their blades, each with the coefficient
/// s_a s_b c for the signs s_a and s_b of the two blades. Writes the first
/// out.size() terms to `out` and returns the number of all terms, so a call
/// with an empty `out` only counts them, and a second call with `out` of that
/// size writes them all.
///
/// Requires: every sign of `as` and `bs` is +1 or -1, which is not checked
/// here; every mask names only e_1 to e_N, and Capacity suffices for every
/// pair, as plan_capacity(Op, as, bs) does, each checked by GALOOT_ASSERT
/// in pair_terms. Every coefficient fits coefficient_type, checked by
/// GALOOT_ASSERT.
/// Guarantees: no term has a zero coefficient, and within one pair no blade
/// appears twice. A mask listed twice in a set is not rejected; each place
/// that lists it gets its own terms. Places of `out` past the number of terms
/// are not written.
template <BinaryOperation Op, std::size_t Capacity, std::size_t N>
constexpr std::size_t generate_plan(const metric<N>& g,
                                    std::span<const oriented_blade> as,
                                    std::span<const oriented_blade> bs,
                                    std::span<plan_term> out) noexcept {
  std::size_t count = 0;
  for (std::size_t a = 0; a < as.size(); ++a) {
    for (std::size_t b = 0; b < bs.size(); ++b) {
      const term_list<Capacity> terms =
          pair_terms<Op, Capacity>(g, as[a].mask, bs[b].mask);
      // A sign of +1 or -1 times a coefficient within -max to max cannot
      // overflow, so the product needs no guard.
      const coefficient_type sign =
          static_cast<coefficient_type>(as[a].sign) * bs[b].sign;
      for (std::size_t k = 0; k < terms.size(); ++k) {
        if (count < out.size()) {
          out[count] = {
              .a = a,
              .b = b,
              .out = terms.terms[k].blade,
              .coefficient = sign * terms.terms[k].coefficient,
          };
        }
        ++count;
      }
    }
  }
  return count;
}

/// Writes the distinct output blades of the terms of `plan` to `out`, each
/// once and with sign +1, in canonical order of their blades, and returns
/// their number.
///
/// Requires: `out` has a place for every distinct blade, checked by
/// GALOOT_ASSERT; plan.size() places always suffice.
/// Guarantees: the first places of `out`, up to the number returned, hold
/// every blade that a term of `plan` names and no other, in strictly
/// increasing canonical order. The other places are not written.
constexpr std::size_t collect_result(std::span<const plan_term> plan,
                                     std::span<oriented_blade> out) noexcept {
  std::size_t size = 0;
  for (const plan_term& t : plan) {
    std::size_t at = 0;
    while (at < size && canonical_less(out[at].mask, t.out)) {
      ++at;
    }
    if (at < size && out[at].mask == t.out) {
      continue;
    }
    GALOOT_ASSERT(size < out.size(), "more result blades than places for them");
    for (std::size_t j = size; j > at; --j) {
      out[j] = out[j - 1];
    }
    out[at] = {.mask = t.out, .sign = 1};
    ++size;
  }
  return size;
}

/// One term of a typed plan: the blade at position `a` of the first set
/// times the blade at position `b` of the second contributes coefficient
/// times the blade at position `out` of the plan's result set.
///
/// Guarantees: an aggregate, trivially copyable; two terms are equal when
/// every member is.
struct typed_term {
  /// The position of the first factor's blade in the first set.
  std::size_t a;
  /// The position of the second factor's blade in the second set.
  std::size_t b;
  /// The position of the output blade in the result set.
  std::size_t out;
  /// The exact coefficient, with the signs of both input blades folded in.
  coefficient_type coefficient;

  /// Equal when every member is equal.
  [[nodiscard]] constexpr bool operator==(const typed_term&) const = default;
};

/// Writes the terms of `plan` to `out`, as many as fit, each with the
/// position in `result` of its blade in place of the blade.
///
/// Requires: nothing.
/// Guarantees: the term at position k of `out` has the positions and the
/// coefficient of the term at k of `plan`, and the position in `result` of
/// the first blade with its mask, or result.size() if no blade has it.
/// Places of `out` past plan.size() are not written.
constexpr void type_terms(std::span<const plan_term> plan,
                          std::span<const oriented_blade> result,
                          std::span<typed_term> out) noexcept {
  for (std::size_t k = 0; k < plan.size() && k < out.size(); ++k) {
    std::size_t at = 0;
    while (at < result.size() && result[at].mask != plan[k].out) {
      ++at;
    }
    out[k] = {
        .a = plan[k].a,
        .b = plan[k].b,
        .out = at,
        .coefficient = plan[k].coefficient,
    };
  }
}

/// A plan typed onto the blade set of its result: R result blades and T
/// terms.
///
/// Guarantees: a structural, trivially copyable aggregate; two plans are
/// equal when their result sets and their terms are.
template <std::size_t R, std::size_t T>
struct typed_plan {
  /// The blades of the result, each with sign +1, in canonical order.
  blade_set<R> result;
  /// The terms, in order of a, then b, then position in the result.
  std::array<typed_term, T> terms;

  /// Equal when the result sets and the terms are equal.
  [[nodiscard]] constexpr bool operator==(const typed_plan&) const = default;
};

// Whether every blade of `set` names only e_1 to e_n.
template <std::size_t K>
[[nodiscard]] constexpr bool all_in_algebra(const blade_set<K>& set,
                                            std::size_t n) noexcept {
  // NOLINTNEXTLINE(readability-use-anyofallof): avoids <algorithm> here.
  for (const oriented_blade& blade : set.blades) {
    if (!in_algebra(blade.mask, n)) {
      return false;
    }
  }
  return true;
}

// What is wrong with a generated plan, if anything. None of these can hold for
// a plan that generate_plan wrote; they are checked once per plan, because
// each check is one pass over the terms.
struct plan_defects {
  bool zero_coefficient;
  bool beyond_first;
  bool beyond_second;
  bool beyond_n;
  bool out_of_order;
};

// The defects of `plan` for sets of `first` and `second` blades in an algebra
// of n generators. The terms must come in order of a, then b, and within one
// pair in strictly increasing canonical order of their blades, so a blade
// listed twice for one pair is out of order too.
[[nodiscard]] constexpr plan_defects defects_of(std::span<const plan_term> plan,
                                                std::size_t first,
                                                std::size_t second,
                                                std::size_t n) noexcept {
  plan_defects found{};
  for (std::size_t k = 0; k < plan.size(); ++k) {
    const plan_term& t = plan[k];
    found.zero_coefficient = found.zero_coefficient || t.coefficient == 0;
    found.beyond_first = found.beyond_first || t.a >= first;
    found.beyond_second = found.beyond_second || t.b >= second;
    found.beyond_n = found.beyond_n || !in_algebra(t.out, n);
    if (k > 0) {
      const plan_term& before = plan[k - 1];
      const bool in_order = before.a < t.a ||
                            (before.a == t.a && before.b < t.b) ||
                            (before.a == t.a && before.b == t.b &&
                             canonical_less(before.out, t.out));
      found.out_of_order = found.out_of_order || !in_order;
    }
  }
  return found;
}

// What is wrong with the typing of a plan, if anything. None of these can
// hold for a plan typed by collect_result and type_terms.
struct typed_defects {
  bool result_out_of_order;
  bool result_sign;
  bool beyond_result;
  bool result_unused;
  bool out_of_order;
};

// The defects of the typed terms `terms` on the result set `result`: the
// result must be in strictly increasing canonical order with every sign +1,
// every position must lie within it, every blade of it must be the output of
// some term, and the terms must come in order of a, then b, and within one
// pair in strictly increasing order of position.
template <std::size_t R>
[[nodiscard]] constexpr typed_defects
typed_defects_of(const blade_set<R>& result,
                 std::span<const typed_term> terms) noexcept {
  typed_defects found{};
  for (std::size_t r = 0; r < R; ++r) {
    found.result_sign = found.result_sign || result.blades[r].sign != 1;
    if (r > 0) {
      found.result_out_of_order =
          found.result_out_of_order ||
          !canonical_less(result.blades[r - 1].mask, result.blades[r].mask);
    }
  }

  std::array<bool, R> used{};
  for (std::size_t k = 0; k < terms.size(); ++k) {
    const typed_term& t = terms[k];
    if (t.out < R) {
      used[t.out] = true;
    } else {
      found.beyond_result = true;
    }
    if (k > 0) {
      const typed_term& before = terms[k - 1];
      const bool in_order =
          before.a < t.a || (before.a == t.a && before.b < t.b) ||
          (before.a == t.a && before.b == t.b && before.out < t.out);
      found.out_of_order = found.out_of_order || !in_order;
    }
  }
  // NOLINTNEXTLINE(readability-use-anyofallof): avoids <algorithm> here.
  for (const bool is_used : used) {
    found.result_unused = found.result_unused || !is_used;
  }
  return found;
}

template <BinaryOperation Op, std::size_t Count, std::size_t Capacity,
          std::size_t N>
[[nodiscard]] constexpr std::array<plan_term, Count>
filled_plan(const metric<N>& g, std::span<const oriented_blade> as,
            std::span<const oriented_blade> bs) noexcept {
  std::array<plan_term, Count> plan{};
  generate_plan<Op, Capacity>(g, as, bs, plan);
  return plan;
}

// The result blades of a plan of T terms, in the first `size` places.
template <std::size_t T>
struct collected_result {
  std::array<oriented_blade, T> blades;
  std::size_t size;
};

template <std::size_t T>
[[nodiscard]] constexpr collected_result<T>
collected(const std::array<plan_term, T>& plan) noexcept {
  collected_result<T> found{};
  found.size = collect_result(plan, found.blades);
  return found;
}

template <std::size_t R, std::size_t T>
[[nodiscard]] constexpr typed_plan<R, T>
typed(const std::array<plan_term, T>& plan,
      const collected_result<T>& found) noexcept {
  typed_plan<R, T> typed_plan_of{};
  for (std::size_t r = 0; r < R; ++r) {
    typed_plan_of.result.blades[r] = found.blades[r];
  }
  type_terms(plan, typed_plan_of.result.blades, typed_plan_of.terms);
  return typed_plan_of;
}

// Checks both sets once, before anything is generated, so that a misuse gives
// its own message and no other. Then counts the terms, fills an array of that
// size, checks what is cheap to check of it, types it onto its result set,
// and checks the typing.
//
// Every local is static constexpr: its initializer is evaluated once, when
// the function is instantiated. Clang evaluates the initializer of a plain
// constexpr local again each time the call is evaluated, so the plan would be
// generated twice, once for the static_asserts and once for the call.
template <BinaryOperation Op, metric_like Alg, blade_set A, blade_set B>
[[nodiscard]] consteval auto make_product_plan() {
  static constexpr std::size_t n = Alg::value.generator_count;
  static constexpr bool in_range = all_in_algebra(A, n) && all_in_algebra(B, n);
  static constexpr bool valid_signs = signs_valid<A> && signs_valid<B>;
  static_assert(in_range,
                "product plan: a blade set names a generator beyond e_n");
  static_assert(valid_signs,
                "product plan: a blade set holds a sign other than +1 or -1");

  if constexpr (in_range && valid_signs) {
    static constexpr std::size_t capacity =
        plan_capacity(Op, A.blades, B.blades);
    static constexpr std::size_t count =
        generate_plan<Op, capacity>(Alg::value, A.blades, B.blades, {});
    static constexpr auto generated =
        filled_plan<Op, count, capacity>(Alg::value, A.blades, B.blades);

    static constexpr plan_defects defects =
        defects_of(generated, A.size(), B.size(), n);
    static_assert(!defects.zero_coefficient,
                  "product plan: a generated term has a zero coefficient");
    static_assert(!defects.beyond_first,
                  "product plan: a generated term points past the first set");
    static_assert(!defects.beyond_second,
                  "product plan: a generated term points past the second set");
    static_assert(!defects.beyond_n,
                  "product plan: a generated term has a generator beyond e_n");
    static_assert(!defects.out_of_order,
                  "product plan: generated terms are out of order or repeated");

    static constexpr auto found = collected(generated);
    static constexpr auto plan = typed<found.size>(generated, found);
    static constexpr typed_defects typing =
        typed_defects_of(plan.result, plan.terms);
    static_assert(!typing.result_out_of_order,
                  "product plan: the result set is out of canonical order or "
                  "repeats a blade");
    static_assert(!typing.result_sign,
                  "product plan: the result set holds a sign other than +1");
    static_assert(!typing.beyond_result,
                  "product plan: a typed term points past the result set");
    static_assert(!typing.result_unused,
                  "product plan: the result set holds a blade that no term "
                  "uses");
    static_assert(!typing.out_of_order,
                  "product plan: typed terms are out of order or repeated");
    return plan;
  } else {
    return typed_plan<0, 0>{};
  }
}

/// The plan of the product `Op` of a multivector on the blade set A with one
/// on the blade set B, in the algebra of the tag Alg, typed onto the blade set
/// of its result: a typed_plan whose result set holds every blade a term
/// lands on, once, with sign +1, in canonical order, and whose terms come in
/// order of a, then b, then position in the result set.
///
/// Requires: Alg is metric_like. Every blade of A and B names only e_1 to
/// e_n and has sign +1 or -1, each checked at compile time with a message
/// that names it. Every coefficient fits coefficient_type, checked as the
/// plan is generated. A mask listed twice in one set is not checked; each
/// place that lists it gets its own terms, which may land on one position
/// of the result. The plan is a constant evaluation, so the compiler's
/// limits on constant evaluation bound the size of the sets in practice.
/// Measured at the default limits, alike at -O0 and -O2 and with or without
/// _GLIBCXX_ASSERTIONS: every blade times every blade, full<n> with full<n>,
/// builds for n up to 5 on Clang 23 and up to 6 on GCC 16, for both
/// operations, in R(n,0,0), R(n-1,0,1), and conformal(n-2); in a form with
/// every entry nonzero, whose products have more terms, the geometric
/// product builds for n up to 4 on Clang and 5 on GCC, and the wedge, which
/// does not read the form, as in the others. Sets of a few blades cost what
/// they use: four blades times three at n = 16 build on both.
/// Guarantees: generated once in each translation unit for each Op, Alg, A,
/// and B that it uses, because the generator keeps its steps in static
/// constexpr locals (checked on Clang, where plain locals would generate it
/// twice; GCC's cache of constant calls hides a repetition). No term has a zero
/// coefficient, a refers to a position of A and b to one of B, and out to one
/// of the result set, every blade of which is the output of some term; each is
/// checked when the plan is generated.
template <BinaryOperation Op, metric_like Alg, blade_set A, blade_set B>
// clang-tidy reads the operation, once substituted, as a C-style cast of its
// value, which the source does not have.
// NOLINTNEXTLINE(modernize-avoid-c-style-cast)
inline constexpr auto product_plan = make_product_plan<Op, Alg, A, B>();

